import pandas as pd
import numpy as np

def transform(source: pd.DataFrame) -> pd.DataFrame:
    """
    Transforms source DataFrame with high-frequency data into a daily hourly summary.
    """
    df = source.copy()
    
    # 1. Parse the date column
    df['datetime'] = pd.to_datetime(df['date'])
    
    # 2. Extract date string for grouping and formatting
    df['date_str'] = df['datetime'].dt.strftime('%m/%d/%Y')
    
    # 3. Extract hour (0-23)
    df['hour'] = df['datetime'].dt.hour
    
    # 4. Map hour to target column name
    # Logic inferred: Hour 0 (midnight) maps to 'Hour 24'. 
    # Hours 1-23 map to 'Hour 1' through 'Hour 23'.
    def get_target_col(h):
        if h == 0:
            return 'Hour 24'
        else:
            return f'Hour {h}'
            
    df['target_col'] = df['hour'].apply(get_target_col)
    
    # 5. Aggregate data
    # We group by date_str and target_col, then aggregate the zone_016 values.
    # Using mean to handle multiple entries per hour.
    pivot_data = df.groupby(['date_str', 'target_col'])['zone_016'].mean().reset_index()
    
    # 6. Pivot to wide format
    # Each row is a date, columns are Hour 1..24
    df_pivot = pivot_data.pivot(index='date_str', columns='target_col', values='zone_016')
    
    # 7. Ensure all hour columns exist and are in correct order
    target_cols = [f'Hour {i}' for i in range(1, 25)]
    
    # Reindex columns to ensure all Hour 1-24 are present, filling missing with NaN
    df_pivot = df_pivot.reindex(columns=target_cols)
    
    # 8. Reset index to make date a column
    df_pivot = df_pivot.reset_index()
    
    # 9. Rename the date column to 'date'
    df_pivot = df_pivot.rename(columns={'date_str': 'date'})
    
    # 10. Select final columns verbatim
    final_cols = ['date'] + target_cols
    result = df_pivot[final_cols]
    
    # Optional: Sort by date if required? The sample shows 01/02 then 01/01. 
    # Usually, we preserve order or sort ascending. The prompt doesn't specify sort order, 
    # but standard practice is often ascending date. However, the sample target is 
    # 01/02 then 01/01. This looks like descending or just the order of appearance.
    # Given the ambiguity, we will leave the order as generated by groupby/pivot, 
    # which typically sorts by the index (date_str). 
    # Let's check if the sample implies a specific sort. 
    # Source sample has 1/2 then 1/3. 
    # Target sample has 01/02 then 01/01. 
    # It's safer to just return the dataframe. If sorting is needed, 
    # ascending is the default pandas behavior for groupby/pivot index.
    
    return result